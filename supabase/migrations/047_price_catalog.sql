-- ============================================================
-- SERVICE PRICE CATALOG
-- ============================================================
-- /admin/price-list keeps every service, add-on and fee; the estimate and
-- invoice builder (Add from price list) drawer inserts them into the Items
-- box as typed lines (src/lib/priceCatalog.ts). Prices are copied in at that
-- moment, so changing the catalog never changes a saved estimate or invoice.
--
-- price_items.price is in dollars (null/0 for included items; the hourly rate
-- for hourly items, with hours). unit marks per-unit items that get a quantity
-- box ("page", "slide"…). price_item_rules: "requires" adds the other item
-- automatically (and the builder will not save without it); "suggests" offers it.
--
-- Admin only: RLS on with no policies, like estimates and the vault. Clients
-- never see the catalog.
--
-- Also: totals_only on estimates and invoices. On, the PDF for the client shows
-- category subtotals instead of every line. Existing rows stay off (their
-- PDFs do not change); new ones default to on.
--
-- Seeded from docs/thrive-price-list.md. Safe to run more than once.

create table if not exists public.price_categories (
  id          uuid primary key default gen_random_uuid(),
  name        text not null unique,
  description text not null default '',
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.price_items (
  id          uuid primary key default gen_random_uuid(),
  category_id uuid not null references public.price_categories(id) on delete restrict,
  name        text not null,
  description text not null default '',
  price       numeric(12, 2),
  price_type  text not null default 'flat' check (price_type in ('flat', 'hourly', 'included', 'monthly')),
  hours       numeric(8, 2),
  is_optional boolean not null default false,
  is_active   boolean not null default true,
  sort_order  integer not null default 0,
  unit        text,
  notes       text not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists price_items_category_idx on public.price_items (category_id, sort_order);

create table if not exists public.price_item_rules (
  id              uuid primary key default gen_random_uuid(),
  item_id         uuid not null references public.price_items(id) on delete cascade,
  rule_type       text not null check (rule_type in ('requires', 'suggests')),
  related_item_id uuid not null references public.price_items(id) on delete cascade,
  created_at      timestamptz not null default now(),
  unique (item_id, rule_type, related_item_id),
  check (item_id <> related_item_id)
);

alter table public.price_categories enable row level security;
alter table public.price_items      enable row level security;
alter table public.price_item_rules enable row level security;
revoke all on public.price_categories, public.price_items, public.price_item_rules from anon, authenticated;

-- Existing rows get false; the default then turns on for new ones.
alter table public.estimates       add column if not exists totals_only boolean not null default false;
alter table public.portal_invoices add column if not exists totals_only boolean not null default false;
alter table public.estimates       alter column totals_only set default true;
alter table public.portal_invoices alter column totals_only set default true;

